"""SQLAlchemy models for epaData.

Written in SQLAlchemy 2.0 typed declarative style: columns are declared with
``Mapped[...]`` annotations, and ``Mapped[Optional[...]]`` marks a column
nullable without repeating ``nullable=True``.

Schema overview::

    Dataset  1---* AnnualRecord *---1  Unit  *---1  Facility
       |
       +--1 DataProvenance        (where the data came from, with what query)
       +--1 UploadedFile          (the original file / API response as received)
       +--* DataQualityIssue      (every rejected or flagged source row)

Units of measure follow CAMPD: operating time in hours, gross load in MWh,
steam load in 1000 lb, heat input in MMBtu, and CO2/SO2/NOx mass in short tons.
"""

from datetime import date, datetime, timezone
from typing import Optional

from sqlalchemy import (
    CheckConstraint,
    Date,
    DateTime,
    ForeignKey,
    Index,
    String,
    Text,
    UniqueConstraint,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app import db

# Hours in a leap year: the most a unit can operate in one reporting year.
MAX_OPERATING_HOURS = 8784


def utcnow() -> datetime:
    """Timezone-aware UTC timestamp used as a column default."""
    return datetime.now(timezone.utc)


class Dataset(db.Model):
    """One ingestion run: a single file or API pull from an EPA source."""

    __tablename__ = "datasets"

    id: Mapped[int] = mapped_column(primary_key=True)
    dataset_name: Mapped[str] = mapped_column(String(150))
    data_source: Mapped[str] = mapped_column(String(150))
    reporting_year: Mapped[int]
    retrieval_date: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=utcnow
    )
    original_filename: Mapped[Optional[str]] = mapped_column(String(255))
    raw_records: Mapped[int] = mapped_column(default=0)
    accepted_records: Mapped[int] = mapped_column(default=0)
    notes: Mapped[Optional[str]] = mapped_column(Text)

    annual_records: Mapped[list["AnnualRecord"]] = relationship(
        back_populates="dataset",
        cascade="all, delete-orphan",
    )
    provenance: Mapped[Optional["DataProvenance"]] = relationship(
        back_populates="dataset",
        cascade="all, delete-orphan",
        uselist=False,
    )
    uploaded_file: Mapped[Optional["UploadedFile"]] = relationship(
        back_populates="dataset",
        cascade="all, delete-orphan",
        uselist=False,
    )
    issues: Mapped[list["DataQualityIssue"]] = relationship(
        back_populates="dataset",
        cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:
        return f"<Dataset {self.id} {self.dataset_name!r} ({self.reporting_year})>"


class Facility(db.Model):
    """A power plant / emissions facility, keyed by its EPA-assigned ID."""

    __tablename__ = "facilities"

    # EPA assigns this ID, so it is never auto-generated by the database.
    epa_facility_id: Mapped[int] = mapped_column(primary_key=True, autoincrement=False)
    facility_name: Mapped[str] = mapped_column(String(255), index=True)
    state_code: Mapped[str] = mapped_column(String(2), index=True)
    county: Mapped[Optional[str]] = mapped_column(String(100), index=True)
    latitude: Mapped[Optional[float]]
    longitude: Mapped[Optional[float]]
    source_category: Mapped[Optional[str]] = mapped_column(String(150))

    units: Mapped[list["Unit"]] = relationship(
        back_populates="facility",
        cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:
        return f"<Facility {self.epa_facility_id} {self.facility_name!r}>"


class Unit(db.Model):
    """A single combustion / generating unit belonging to a facility.

    ``epa_unit_id`` is only unique within a facility, so an internal surrogate
    key is used as the primary key. Type and fuel describe the unit as of the
    most recent reporting year ingested.
    """

    __tablename__ = "units"
    __table_args__ = (
        # ``epa_unit_id`` is unique only within a facility. The constraint lets
        # ingestion upsert a unit on its natural key instead of duplicating it
        # on every re-upload.
        UniqueConstraint("facility_id", "epa_unit_id", name="uq_facility_epa_unit"),
    )

    internal_unit_key: Mapped[int] = mapped_column(primary_key=True)
    facility_id: Mapped[int] = mapped_column(
        ForeignKey("facilities.epa_facility_id", ondelete="CASCADE"),
        index=True,
    )
    epa_unit_id: Mapped[str] = mapped_column(String(50), index=True)
    unit_type: Mapped[str] = mapped_column(String(100), index=True)
    primary_fuel: Mapped[str] = mapped_column(String(100), index=True)
    secondary_fuel: Mapped[Optional[str]] = mapped_column(String(100))
    operating_date: Mapped[Optional[date]] = mapped_column(Date)
    retirement_date: Mapped[Optional[date]] = mapped_column(Date)

    facility: Mapped["Facility"] = relationship(back_populates="units")
    annual_records: Mapped[list["AnnualRecord"]] = relationship(
        back_populates="unit",
        cascade="all, delete-orphan",
    )

    def __repr__(self) -> str:
        return f"<Unit {self.internal_unit_key} facility={self.facility_id} {self.epa_unit_id!r}>"


class AnnualRecord(db.Model):
    """Annual emissions and operating totals reported for one unit."""

    __tablename__ = "annual_records"
    __table_args__ = (
        UniqueConstraint("unit_id", "reporting_year", name="uq_unit_reporting_year"),
        # The ingestion pipeline already rejects these rows; the constraints
        # are the database's own guarantee, covering any other write path.
        CheckConstraint(
            "reporting_year BETWEEN 1980 AND 2100", name="ck_annual_records_year_range"
        ),
        CheckConstraint(
            f"operating_time >= 0 AND operating_time <= {MAX_OPERATING_HOURS}",
            name="ck_annual_records_operating_time",
        ),
        CheckConstraint(
            "gross_load >= 0 AND heat_input >= 0 "
            "AND (steam_load IS NULL OR steam_load >= 0)",
            name="ck_annual_records_load_nonnegative",
        ),
        CheckConstraint(
            "co2_mass >= 0 AND so2_mass >= 0 AND nox_mass >= 0",
            name="ck_annual_records_mass_nonnegative",
        ),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    unit_id: Mapped[int] = mapped_column(
        ForeignKey("units.internal_unit_key", ondelete="CASCADE"),
        index=True,
    )
    dataset_id: Mapped[int] = mapped_column(
        ForeignKey("datasets.id", ondelete="CASCADE"),
        index=True,
    )
    reporting_year: Mapped[int] = mapped_column(index=True)

    operating_time: Mapped[float] = mapped_column(index=True)
    gross_load: Mapped[float] = mapped_column(index=True)
    steam_load: Mapped[Optional[float]]
    heat_input: Mapped[float] = mapped_column(index=True)

    co2_mass: Mapped[float] = mapped_column(index=True)
    so2_mass: Mapped[float] = mapped_column(index=True)
    nox_mass: Mapped[float] = mapped_column(index=True)

    so2_control: Mapped[Optional[str]] = mapped_column(String(150))
    nox_control: Mapped[Optional[str]] = mapped_column(String(150))
    pm_control: Mapped[Optional[str]] = mapped_column(String(150))
    program_code: Mapped[Optional[str]] = mapped_column(String(100))

    unit: Mapped["Unit"] = relationship(back_populates="annual_records")
    dataset: Mapped["Dataset"] = relationship(back_populates="annual_records")

    def __repr__(self) -> str:
        return f"<AnnualRecord unit={self.unit_id} year={self.reporting_year}>"


class UploadedFile(db.Model):
    """A file as received -- an upload, or a saved CAMPD API response.

    Created when the file is staged for review, before any dataset exists;
    linked to its dataset once the import is approved.
    """

    __tablename__ = "uploaded_files"

    id: Mapped[int] = mapped_column(primary_key=True)
    dataset_id: Mapped[Optional[int]] = mapped_column(
        ForeignKey("datasets.id", ondelete="CASCADE"), index=True
    )
    # "upload" for a user file, "api" for a CAMPD API retrieval.
    source_type: Mapped[str] = mapped_column(String(20))
    original_filename: Mapped[str] = mapped_column(String(255))
    # Name of the copy kept under UPLOAD_FOLDER.
    stored_filename: Mapped[str] = mapped_column(String(255), unique=True)
    file_extension: Mapped[str] = mapped_column(String(10))
    file_size: Mapped[int]
    sha256: Mapped[str] = mapped_column(String(64), index=True)
    uploaded_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    # staged -> imported | discarded
    status: Mapped[str] = mapped_column(String(20), default="staged")
    dataset_name: Mapped[Optional[str]] = mapped_column(String(150))
    # API retrievals only: endpoint (never including the key) and filters.
    source_url: Mapped[Optional[str]] = mapped_column(String(500))
    query_params: Mapped[Optional[str]] = mapped_column(Text)

    dataset: Mapped[Optional["Dataset"]] = relationship(back_populates="uploaded_file")

    def __repr__(self) -> str:
        return f"<UploadedFile {self.id} {self.original_filename!r} {self.status}>"


class DataProvenance(db.Model):
    """Where one dataset came from and how it was obtained."""

    __tablename__ = "data_provenance"

    id: Mapped[int] = mapped_column(primary_key=True)
    dataset_id: Mapped[int] = mapped_column(
        ForeignKey("datasets.id", ondelete="CASCADE"), unique=True
    )
    source_type: Mapped[str] = mapped_column(String(20))
    source_name: Mapped[str] = mapped_column(String(255))
    source_url: Mapped[Optional[str]] = mapped_column(String(500))
    query_params: Mapped[Optional[str]] = mapped_column(Text)
    original_filename: Mapped[Optional[str]] = mapped_column(String(255))
    file_sha256: Mapped[Optional[str]] = mapped_column(String(64))
    retrieved_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    reporting_years: Mapped[Optional[str]] = mapped_column(String(100))
    raw_records: Mapped[int] = mapped_column(default=0)
    accepted_records: Mapped[int] = mapped_column(default=0)
    rejected_records: Mapped[int] = mapped_column(default=0)
    warning_records: Mapped[int] = mapped_column(default=0)
    notes: Mapped[Optional[str]] = mapped_column(Text)

    dataset: Mapped["Dataset"] = relationship(back_populates="provenance")


class DataQualityIssue(db.Model):
    """One problem found in one source row during validation.

    ``severity`` is "rejected" when the row was not imported, or "warning" when
    it was imported with a value defaulted, cleared, or truncated. Key fields are
    kept as the raw text from the file, since a rejected row may not have
    parseable keys at all.
    """

    __tablename__ = "data_quality_issues"
    __table_args__ = (
        Index("ix_data_quality_issues_dataset_severity", "dataset_id", "severity"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)
    dataset_id: Mapped[int] = mapped_column(
        ForeignKey("datasets.id", ondelete="CASCADE")
    )
    source_row: Mapped[Optional[int]]
    severity: Mapped[str] = mapped_column(String(10))
    issue_type: Mapped[str] = mapped_column(String(40))
    field: Mapped[Optional[str]] = mapped_column(String(60))
    message: Mapped[str] = mapped_column(Text)
    facility_id: Mapped[Optional[str]] = mapped_column(String(50))
    epa_unit_id: Mapped[Optional[str]] = mapped_column(String(50))
    reporting_year: Mapped[Optional[str]] = mapped_column(String(20))
    raw_values: Mapped[Optional[str]] = mapped_column(Text)

    dataset: Mapped["Dataset"] = relationship(back_populates="issues")
